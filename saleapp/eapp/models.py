from sqlalchemy import Column, Integer, String, Float, Text, ForeignKey
from sqlalchemy.orm import relationship
from unicodedata import category

from eapp import db, app


class Category(db.Model):
    id = Column(Integer, primary_key=True, autoincrement=True) #khóa chính, tự tăng id
    name = Column(String(50), nullable=False, unique=True) #tên có tối đa 50 ký tự, không được để trống, không trùng tên
    products = relationship('Product', backref='category', lazy=True)

    def __str__(self):
        return self.name


class Product(db.Model):
    id = Column(Integer, primary_key=True, autoincrement=True)  # khóa chính, tự tăng id
    name = Column(String(50), nullable=False)  # tên có tối đa 50 ký tự, không được để trống, không trùng tên
    description = Column(Text, nullable=True)
    image = Column(String(100))
    price = Column(Float, default=0)
    category_id = Column(Integer, ForeignKey(Category.id), nullable=False)

    def __str__(self):
        return self.name


